/**
 * Builds the prebuilt OpenScreen bundles shipped in the npm package:
 *
 *   dist/renderer/            static browser app (renderer/main.ts + vendored OpenScreen exporter,
 *                             pixi.js, mediabunny, web-demuxer wasm, wallpapers, cursor assets)
 *   dist/openscreen/project.js  OpenScreen's project validation for Node (renderer/node-project.ts)
 *
 * Usage: node scripts/build-renderer.ts   (or bun scripts/build-renderer.ts)
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VENDOR = path.join(ROOT, "vendor/openscreen");
const alias = { "@": path.join(VENDOR, "src") };

/** npm packages whose code ends up in a bundle (for THIRD_PARTY_NOTICES.md). */
const bundled = new Map<string, string>();
const collect = {
	name: "demoreel-collect-packages",
	generateBundle(_: unknown, bundle: Record<string, { type: string; moduleIds?: string[] }>) {
		for (const chunk of Object.values(bundle)) {
			for (const id of chunk.moduleIds ?? []) {
				const m = /node_modules[\\/]((?:@[^\\/]+[\\/])?[^\\/]+)/.exec(id.replace(/^\0/, ""));
				if (m) bundled.set(m[1].replace(/\\/g, "/"), path.join(id.slice(0, m.index), "node_modules", m[1]));
			}
		}
	},
};

const rendererOut = path.join(ROOT, "dist/renderer");
await build({
	configFile: false,
	root: path.join(ROOT, "renderer"),
	base: "./",
	publicDir: path.join(VENDOR, "public"),
	logLevel: "warn",
	resolve: { alias },
	build: {
		outDir: rendererOut,
		emptyOutDir: true,
		target: "es2022",
		chunkSizeWarningLimit: 4096,
		reportCompressedSize: false,
		assetsInlineLimit: 0,
	},
	plugins: [collect],
});

// web-demuxer loads its wasm from ./wasm/web-demuxer.wasm relative to the page.
const wasm = path.join(ROOT, "node_modules/web-demuxer/dist/wasm-files/web-demuxer.wasm");
fs.mkdirSync(path.join(rendererOut, "wasm"), { recursive: true });
fs.copyFileSync(wasm, path.join(rendererOut, "wasm/web-demuxer.wasm"));

const projectOut = path.join(ROOT, "dist/openscreen");
await build({
	configFile: false,
	root: ROOT,
	logLevel: "warn",
	resolve: { alias },
	publicDir: false,
	build: {
		outDir: projectOut,
		emptyOutDir: true,
		target: "node20",
		minify: false,
		reportCompressedSize: false,
		lib: { entry: path.join(ROOT, "renderer/node-project.ts"), formats: ["es"], fileName: () => "project.js" },
		rollupOptions: { external: [/^node:/] },
	},
	plugins: [collect],
});

// Assets referenced via `new URL(..., import.meta.url)` are not modules: add their packages.
if (fs.readdirSync(path.join(rendererOut, "assets")).some((f) => f.startsWith("gif.worker"))) {
	bundled.set("gif.js", path.join(ROOT, "node_modules/gif.js"));
}
bundled.set("web-demuxer", path.join(ROOT, "node_modules/web-demuxer")); // wasm copied above

// Licences: OpenScreen (vendored sources) + every npm package bundled into dist/.
const licDir = path.join(ROOT, "licenses");
fs.rmSync(licDir, { recursive: true, force: true });
fs.mkdirSync(licDir);
fs.copyFileSync(path.join(VENDOR, "LICENSE"), path.join(licDir, "openscreen.txt"));
const vendored = fs.readFileSync(path.join(VENDOR, "VENDORED.md"), "utf8");
const commit = /commit `([0-9a-f]+)`/.exec(vendored)?.[1] ?? "unknown";
const rows: string[] = [];
for (const [name, dir] of [...bundled].sort(([a], [b]) => a.localeCompare(b))) {
	const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
	const licFile = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
	const file = `${name.replace("/", "__")}.txt`;
	const text = licFile ? fs.readFileSync(path.join(dir, licFile), "utf8") : "";
	const license =
		typeof pkg.license === "string"
			? pkg.license
			: (pkg.license?.type ?? (/^\s*MIT License/.test(text) ? "MIT" : "see file"));
	if (licFile) fs.copyFileSync(path.join(dir, licFile), path.join(licDir, file));
	else fs.writeFileSync(path.join(licDir, file), `${name} ${pkg.version}: ${license} (no licence file in the package)\n`);
	const repo = typeof pkg.repository === "string" ? pkg.repository : (pkg.repository?.url ?? "");
	rows.push(`| ${name} | ${pkg.version} | ${license} | [licenses/${file}](licenses/${file}) | ${repo.replace(/^git\+/, "").replace(/\.git$/, "")} |`);
}
fs.writeFileSync(
	path.join(ROOT, "THIRD_PARTY_NOTICES.md"),
	`# Third-party notices

demoreel's prebuilt renderer (\`dist/renderer/\`) and \`dist/openscreen/project.js\` are bundled
from third-party code. Generated by \`scripts/build-renderer.ts\`.

## OpenScreen

Unmodified source files from [OpenScreen](https://github.com/siddharthvaddem/openscreen)
(commit \`${commit}\`, MIT License, Copyright (c) 2025 Siddharth Vaddem), including its
cursor and wallpaper assets: [licenses/openscreen.txt](licenses/openscreen.txt). The exact files
are listed in \`vendor/openscreen/VENDORED.md\` in the demoreel repository.

## npm packages bundled into dist/

| package | version | license | text | source |
| --- | --- | --- | --- | --- |
${rows.join("\n")}

MPL-2.0 code (mediabunny) is included unmodified; its source is available from the
repository linked above and from the npm package of the listed version.
`,
);

const size = (dir: string): number =>
	fs.readdirSync(dir, { withFileTypes: true }).reduce((n, e) => {
		const p = path.join(dir, e.name);
		return n + (e.isDirectory() ? size(p) : fs.statSync(p).size);
	}, 0);
console.log(
	`built dist/renderer (${(size(rendererOut) / 1e6).toFixed(2)} MB) and dist/openscreen/project.js (${(size(projectOut) / 1e3).toFixed(0)} kB)`,
);
